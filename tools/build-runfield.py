#!/usr/bin/env python3
"""Packages tools/runfield/* into site/js/runfield-src.js (the Monkey C that the data-field element exports).
Edit the .mc files, then run:  python3 tools/build-runfield.py"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
part = open(os.path.join(here, 'runfield', 'RunField.mc.part'), encoding='utf-8').read()
members = part.split('//@members\n', 1)[1].split('//@code\n', 1)[0].rstrip('\n').split('\n')
code = part.split('//@code\n', 1)[1].strip('\n')
code = code.replace('\n    // ===== Run field', '\n    // ===== Run field', 1)
# the first line is emitted with the standard 4-space method indent by the generator
code = code.lstrip()
out = ('/* GENERATED by tools/build-runfield.py from tools/runfield/*. Do not edit by hand. */\n'
       '(function (GW) {\n  \'use strict\';\n  GW.RUNFIELD_SRC = {\n'
       '    members: %s,\n    code: %s\n  };\n})(window.GW);\n') % (
    json.dumps(members, ensure_ascii=False, indent=2), json.dumps(code, ensure_ascii=False))
open(os.path.join(here, '..', 'site', 'js', 'runfield-src.js'), 'w', encoding='utf-8').write(out)
print('wrote site/js/runfield-src.js (%d members, %d chars of code)' % (len(members), len(code)))

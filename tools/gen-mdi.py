#!/usr/bin/env python3
"""Builds the icon library of Garmin Studio from Material Design Icons (Pictogrammers, Apache-2.0) 4.9.95.

  python3 tools/gen-mdi.py            # writes site/fonts/mdi-icons.woff2 and site/js/mdiall.js

After it, run tools/add-mdi-extras.py to add the few extra glyphs (Floors: stairs-up).
Needs: pip install fonttools brotli. Only basic-plane characters (<= U+FFFF) are kept: the bitmap-font pipeline walks text one UTF-16 unit at a time.
"""
import io, json, os, re, sys, tarfile, urllib.request
from fontTools import subset
from fontTools.ttLib import TTFont

VER = '4.9.95'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def fetch(pkg, member):
    url = 'https://registry.npmjs.org/@mdi/%s/-/%s-%s.tgz' % (pkg, pkg, VER)
    with urllib.request.urlopen(url, timeout=120) as r:
        data = r.read()
    with tarfile.open(fileobj=io.BytesIO(data), mode='r:gz') as t:
        return t.extractfile('package/' + member).read()

css = fetch('font', 'css/materialdesignicons.css').decode()
ttf = fetch('font', 'fonts/materialdesignicons-webfont.ttf')
meta = json.loads(fetch('svg', 'meta.json').decode())
tags = {m['name']: (m.get('tags') or [], m.get('aliases') or []) for m in meta}

items = [(n, int(c, 16)) for n, c in re.findall(r'\.mdi-([a-z0-9-]+)::before\s*\{\s*content:\s*"\\([0-9A-Fa-f]+)"', css)]
bmp = sorted([(n, c) for n, c in items if c <= 0xFFFF], key=lambda x: x[0])

alltags = sorted({t for n, c in bmp for t in tags.get(n, ([], []))[0]})
rows = []
for n, c in bmp:
    tg, al = tags.get(n, ([], []))
    row = [n, c, [alltags.index(t) for t in tg]]
    if al: row.append(' '.join(al))
    rows.append(row)

js = ['// Material Design Icons @mdi/font %s by Pictogrammers (Apache License 2.0, https://pictogrammers.com/docs/general/license).' % VER,
      '// Generated by tools/gen-mdi.py - do not edit. Basic-plane characters only (%d icons). Row: [name, code point, [tag numbers], aliases].' % len(rows),
      'window.GW = window.GW || {};',
      'GW.MDI_TAGS = ' + json.dumps(alltags, ensure_ascii=False) + ';',
      'GW.MDI_ALL = [']
for r in rows:
    js.append(json.dumps(r, ensure_ascii=False, separators=(',', ':')) + ',')
js.append('];')
os.makedirs(os.path.join(ROOT, 'site/js'), exist_ok=True)
with open(os.path.join(ROOT, 'site/js/mdiall.js'), 'w', encoding='utf-8') as f:
    f.write('\n'.join(js) + '\n')

opts = subset.Options(); opts.layout_features = []; opts.name_IDs = [1, 2]; opts.hinting = False; opts.glyph_names = False; opts.flavor = 'woff2'
font = TTFont(io.BytesIO(ttf))
s = subset.Subsetter(opts); s.populate(unicodes=[c for n, c in bmp]); s.subset(font)
font.flavor = 'woff2'
os.makedirs(os.path.join(ROOT, 'site/fonts'), exist_ok=True)
font.save(os.path.join(ROOT, 'site/fonts/mdi-icons.woff2'))
print('icons:', len(rows), 'tags:', len(alltags))

/* Export: assemble the full Connect IQ project (source, manifest, resources, fonts, images, README, build scripts). */
(function (GW) {
  'use strict';

  function canvasBytes(canvas) {
    return new Promise(function (res, rej) {
      canvas.toBlob(function (b) {
        if (!b) return rej(new Error('PNG encode failed'));
        var fr = new FileReader();
        fr.onload = function () { res(new Uint8Array(fr.result)); };
        fr.readAsArrayBuffer(b);
      }, 'image/png');
    });
  }
  function uuid32() {
    var a = new Uint8Array(16); (window.crypto || window.msCrypto).getRandomValues(a);
    return Array.prototype.map.call(a, function (b) { return (b < 16 ? '0' : '') + b.toString(16); }).join('');
  }
  function scaledImage(asset, w, h) {
    var c = document.createElement('canvas'); c.width = w; c.height = h;
    var x = c.getContext('2d'); x.imageSmoothingQuality = 'high'; x.drawImage(asset.img, 0, 0, w, h);
    return c;
  }
  function xmlEsc(s) { return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;'); }

  function manifest(src, appId, device) {
    return '<?xml version="1.0"?>\n<iq:manifest xmlns:iq="http://www.garmin.com/xml/connectiq" version="3">\n' +
      '    <iq:application entry="' + src.name + 'App" id="' + appId + '" launcherIcon="@Drawables.LauncherIcon" name="@Strings.AppName" type="' + (src.type || 'watchface') + '" minApiLevel="' + (src.minApi || '3.2.0') + '">\n' +
      '        <iq:products>\n            <iq:product id="' + device + '"/>\n        </iq:products>\n' +
      '        <iq:permissions>\n' + src.perms.map(function (p) { return '            <iq:uses-permission id="' + p + '"/>\n'; }).join('') + '        </iq:permissions>\n' +
      '        <iq:languages>\n            <iq:language>eng</iq:language>\n        </iq:languages>\n        <iq:barrels/>\n    </iq:application>\n</iq:manifest>\n';
  }

  function readme(src, design, device, warnings) {
    var n = src.name;
    var field = src.type === 'datafield';
    return '# ' + design.name + ' – ' + GW.DEVICE.name + (field ? ' data field' : ' watchface') + '\n\n' +
      'Generated by **Garmin Watchface Studio**. This folder is a complete Garmin Connect IQ project. You only need to *build* it once and copy one file to your watch.\n\n' +
      '## 1. One-time setup (about 15 minutes)\n\n' +
      '1. Install the **Connect IQ SDK** with the SDK Manager: <https://developer.garmin.com/connect-iq/sdk/> (free; you sign in with a Garmin account).\n' +
      '   In the SDK Manager, download the latest SDK **and** the device **' + GW.DEVICE.name + '** (`' + device + '`).\n' +
      '2. Install **Visual Studio Code** and the **Monkey C** extension (publisher: Garmin).\n' +
      '3. In VS Code run `Monkey C: Verify Installation` (Ctrl/Cmd+Shift+P). If it asks for a developer key, run `Monkey C: Generate a Developer Key` and keep that file safe.\n\n' +
      '## 2. Build the watchface\n\n' +
      '**With VS Code (easiest):** `File > Open Folder` on this folder, then `Monkey C: Build for Device`, choose `' + device + '`, pick an output folder. You get **`' + n + '.prg`**.\n' +
      'To preview first, press **F5** (runs the Garmin simulator).\n\n' +
      '**Or from a terminal:** `./build.sh` (macOS/Linux) or `build.bat` (Windows). It finds your SDK, creates a developer key if you do not have one, and writes `bin/' + n + '.prg`.\n\n' +
      '## 3. Put it on the watch\n\n' +
      '1. Plug the watch into your computer with its USB cable.\n' +
      '2. Open the watch drive (Windows / Linux: it appears as a device; **macOS needs OpenMTP or Android File Transfer**).\n' +
      '3. Copy `' + n + '.prg` into **`GARMIN/APPS`** on the watch.\n' +
      '4. Eject the watch and unplug it.\n' +
      (field
        ? '5. On the watch: **hold UP → Activities & Apps → Run → settings → Data Screens → Add New** (or edit a screen) → choose the **1 field** layout → tap the field → **Connect IQ → ' + design.name + '**.\n\n' +
          'A data field fills the screen and updates once a second during an activity. It cannot create laps itself: the Lap button always works, and for real laps in Garmin Connect switch on the activity’s own Auto Lap (or leave it off for race mode).\n\n'
        : '5. On the watch: **long-press UP → Watch Face → ' + design.name + '**.\n\n' +
          'Sideloaded faces do not show in the Connect IQ phone app; that is normal. Rebuild and copy again whenever you change the design.\n\n') +
      '## Troubleshooting\n\n' +
      '* **"Device not found" / `' + device + '` missing**: open the SDK Manager and download the device files for the ƒēnix 6X Pro / 6X Solar / Sapphire.\n' +
      '* **API level errors**: in `manifest.xml` change `minApiLevel="' + (src.minApi || '3.2.0') + '"` to the level the SDK Manager shows for the device.\n' +
      '* **Watchface shows "IQ!" or crashes**: out of memory. Remove the largest images / bitmap fonts in the designer and export again.\n' +
      '* Data fields showing `--`: the watch has no value yet (weather needs a phone sync; Body Battery / stress need the sensor history).\n\n' +
      (warnings.length ? '## Notes about this design\n\n' + warnings.map(function (w) { return '* ' + w; }).join('\n') + '\n\n' : '') +
      '## What is in this folder\n\n' +
      '```\nmanifest.xml   app id, target device (' + device + '), permissions\nmonkey.jungle  build settings\nsource/        ' + n + 'App.mc, ' + n + 'View.mc (the drawing code)\nresources/     strings, launcher icon' + (src.fonts.length ? ', bitmap fonts' : '') + (src.images.length ? ', images' : '') + '\ndesign.json    re-import this into Watchface Studio to keep editing\n```\n';
  }

  function buildSh(n, device) {
    return '#!/usr/bin/env bash\n# Builds ' + n + '.prg for ' + device + '. Usage: ./build.sh [path/to/developer_key.der]\nset -e\ncd "$(dirname "$0")"\n\n' +
      'SDK=""\nfor cfg in "$HOME/.Garmin/ConnectIQ/current-sdk.cfg" "$HOME/Library/Application Support/Garmin/ConnectIQ/current-sdk.cfg"; do\n  if [ -f "$cfg" ]; then SDK="$(cat "$cfg")"; break; fi\ndone\n' +
      'if [ -n "$CONNECTIQ_HOME" ]; then SDK="$CONNECTIQ_HOME"; fi\nif [ -n "$SDK" ] && [ -x "$SDK/bin/monkeyc" ]; then MONKEYC="$SDK/bin/monkeyc"; else MONKEYC="$(command -v monkeyc || true)"; fi\n' +
      'if [ -z "$MONKEYC" ]; then echo "Could not find the Connect IQ SDK. Install it with the SDK Manager first (see README.md)."; exit 1; fi\n\n' +
      'KEY="${1:-developer_key.der}"\nif [ ! -f "$KEY" ]; then\n  for k in "$HOME/.Garmin/ConnectIQ/developer_key.der" "$HOME/developer_key.der"; do [ -f "$k" ] && KEY="$k" && break; done\nfi\n' +
      'if [ ! -f "$KEY" ]; then\n  echo "No developer key found - creating developer_key.der here. Keep it; you need the same key for future builds."\n  openssl genrsa -out developer_key.pem 4096\n  openssl pkcs8 -topk8 -inform PEM -outform DER -in developer_key.pem -out developer_key.der -nocrypt\n  KEY=developer_key.der\nfi\n\n' +
      'mkdir -p bin\n"$MONKEYC" -d ' + device + ' -f monkey.jungle -o "bin/' + n + '.prg" -y "$KEY" -w\necho\necho "Built bin/' + n + '.prg  ->  copy it to GARMIN/APPS on the watch."\n';
  }
  function buildBat(n, device) {
    return '@echo off\r\nrem Builds ' + n + '.prg for ' + device + '. Usage: build.bat [path\\to\\developer_key.der]\r\ncd /d "%~dp0"\r\n' +
      'set SDK=\r\nif exist "%APPDATA%\\Garmin\\ConnectIQ\\current-sdk.cfg" set /p SDK=<"%APPDATA%\\Garmin\\ConnectIQ\\current-sdk.cfg"\r\nif defined CONNECTIQ_HOME set SDK=%CONNECTIQ_HOME%\r\n' +
      'if not exist "%SDK%\\bin\\monkeyc.bat" ( echo Could not find the Connect IQ SDK. Install it with the SDK Manager first - see README.md & exit /b 1 )\r\n' +
      'set KEY=%~1\r\nif "%KEY%"=="" set KEY=developer_key.der\r\nif not exist "%KEY%" if exist "%USERPROFILE%\\developer_key.der" set KEY=%USERPROFILE%\\developer_key.der\r\n' +
      'if not exist "%KEY%" ( echo No developer key found. In VS Code run "Monkey C: Generate a Developer Key", then run: build.bat path\\to\\developer_key.der & exit /b 1 )\r\n' +
      'if not exist bin mkdir bin\r\ncall "%SDK%\\bin\\monkeyc.bat" -d ' + device + ' -f monkey.jungle -o "bin\\' + n + '.prg" -y "%KEY%" -w\r\n' +
      'echo.\r\necho Built bin\\' + n + '.prg  -^> copy it to GARMIN\\APPS on the watch.\r\n';
  }

  // Resolves to { name, files:[{path,data,exec?}], warnings, src }
  GW.buildProject = function (design) {
    var src = GW.generateSource(design), n = src.name, device = GW.DEVICE.id, files = [], jobs = [];
    var appId = (design.appId && /^[0-9a-f]{32}$/.test(design.appId)) ? design.appId : uuid32();
    function text(path, data, exec) { files.push({ path: path, data: data, exec: exec }); }

    text('manifest.xml', manifest(src, appId, device));
    text('monkey.jungle', 'project.manifest = manifest.xml\n');
    text('source/' + n + 'App.mc', src.app);
    text('source/' + n + 'View.mc', src.view);
    Object.keys(src.files || {}).forEach(function (p) { text(p, src.files[p]); });
    text('resources/strings/strings.xml', '<strings>\n    <string id="AppName">' + xmlEsc(design.name) + '</string>\n</strings>\n');

    var drawables = ['    <bitmap id="LauncherIcon" filename="launcher_icon.png"/>'];
    src.images.forEach(function (m) {
      drawables.push('    <bitmap id="' + m.id + '" filename="images/' + m.id + '.png"/>');
      jobs.push(canvasBytes(scaledImage(GW.assets[m.asset], m.w, m.h)).then(function (b) { text('resources/drawables/images/' + m.id + '.png', b); }));
    });
    if (src.bg) {
      drawables.push('    <bitmap id="bgImage" filename="images/bgImage.png"/>');
      jobs.push(canvasBytes(scaledImage(GW.assets[src.bg.asset], GW.SIZE, GW.SIZE)).then(function (b) { text('resources/drawables/images/bgImage.png', b); }));
    }
    text('resources/drawables/drawables.xml', '<drawables>\n' + drawables.join('\n') + '\n</drawables>\n');

    // launcher icon = the face itself
    var icon = document.createElement('canvas'); icon.width = icon.height = 40;
    var ix = icon.getContext('2d'); ix.scale(40 / GW.SIZE, 40 / GW.SIZE);
    ix.beginPath(); ix.arc(140, 140, 140, 0, Math.PI * 2); ix.clip();
    GW.renderDesign(ix, design, GW.fixedEnv());
    jobs.push(canvasBytes(icon).then(function (b) { text('resources/drawables/launcher_icon.png', b); }));

    if (src.fonts.length) {
      var fx = ['<fonts>'];
      src.fonts.forEach(function (f) {
        var r = GW.rasterizeFont(f);
        fx.push('    <font id="' + f.id + '" filename="' + f.id + '.fnt" antialias="true"/>'); // relative to this xml
        text('resources/fonts/' + f.id + '.fnt', r.fnt);
        jobs.push(canvasBytes(r.canvas).then(function (b) { text('resources/fonts/' + f.id + '.png', b); }));
      });
      fx.push('</fonts>');
      text('resources/fonts/fonts.xml', fx.join('\n') + '\n');
    }

    text('.vscode/launch.json', '{\n    "version": "0.2.0",\n    "configurations": [\n        {\n            "type": "monkeyc",\n            "request": "launch",\n            "name": "Run in simulator",\n            "stopAtLaunch": false,\n            "device": "' + device + '"\n        }\n    ]\n}\n');
    text('build.sh', buildSh(n, device), true);
    text('build.bat', buildBat(n, device));
    text('.gitignore', 'bin/\ndeveloper_key.*\n*.prg\n*.iq\n');
    var saved = GW.serialize(); saved.design.appId = appId;
    text('design.json', JSON.stringify(saved));

    return Promise.all(jobs).then(function () {
      text('README.md', readme(src, design, device, src.warnings));
      var order = ['README.md', 'manifest.xml', 'monkey.jungle'];
      files.sort(function (a, b) {
        var ia = order.indexOf(a.path), ib = order.indexOf(b.path);
        if (ia >= 0 || ib >= 0) return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib);
        return a.path < b.path ? -1 : 1;
      });
      return { name: n, files: files, warnings: src.warnings, src: src, appId: appId };
    });
  };

  // ---- tilt versions: the Big Data face can be exported at several rotations, each as its own app ----
  GW.rotatable = function (design) { return design.elements.some(function (e) { return e.type === 'bigdata' && !e.hidden; }); };
  GW.faceAngle = function (design) {
    var e = design.elements.filter(function (x) { return x.type === 'bigdata'; })[0];
    return e ? e.angle : 0;
  };
  GW.tiltList = function (design) {
    if (!GW.rotatable(design)) return null;
    var t = (design.tilts && design.tilts.length) ? design.tilts.slice() : [GW.faceAngle(design)];
    t = t.map(function (a) { return ((Math.round(a) % 360) + 360) % 360; });
    return t.filter(function (a, i) { return t.indexOf(a) === i; }).sort(function (a, b) { return a - b; });
  };
  // Resolves to an array of project results (one per tilt; a single normal project otherwise).
  GW.buildVariants = function (design) {
    var tl = GW.tiltList(design);
    if (!tl || tl.length < 2) return GW.buildProject(design).then(function (r) { return [r]; });
    design.appIds = design.appIds || {};
    var out = [];
    return tl.reduce(function (p, a) {
      return p.then(function () {
        var d = GW.clone(design);
        d.name = design.name + ' ' + a + '\u00b0';
        d.elements.forEach(function (e) { if (e.type === 'bigdata') e.angle = a; });
        var id = design.appIds[a]; if (!/^[0-9a-f]{32}$/.test(id || '')) id = uuid32();
        design.appIds[a] = id; d.appId = id;
        return GW.buildProject(d).then(function (r) { r.tilt = a; out.push(r); });
      });
    }, Promise.resolve()).then(function () { return out; });
  };

  GW.download = function (blob, filename) {
    var a = document.createElement('a'); a.href = URL.createObjectURL(blob); a.download = filename;
    document.body.appendChild(a); a.click(); a.remove();
    setTimeout(function () { URL.revokeObjectURL(a.href); }, 4000);
  };
})(window.GW);
